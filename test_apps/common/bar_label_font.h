/*!
 * @file
 * @brief Tiny 5x7 bitmap font that draws a short label as solid rectangles.
 *
 * For apps that have no text path of their own (the Linux Vulkan cube) and
 * want to label the zero-disparity tracking status bar
 * (TrackingLossDirector::BarLabel) without a font dependency: each glyph row
 * becomes one rectangle per horizontal run of lit pixels, so the caller can
 * draw the whole label with ONE vkCmdClearAttachments (or ClearView, glScissor
 * + glClear, ...) and no pipeline, texture or shader. Pixel-exact by
 * construction, which is what a zero-disparity label on a lenticular panel
 * wants: the same rects in every view.
 *
 * Upper case only: lower-case letters are drawn as capitals. Covers A-Z, 0-9,
 * space and - ( ) [ ] . : / +; anything else draws as a blank cell.
 *
 * Header-only, no dependencies.
 */
#pragma once

#include <cstdint>
#include <cstring>

namespace dxr_demo {

//! Glyph cell: 5x7 pixels plus one column of spacing.
static constexpr int kBarFontW = 5, kBarFontH = 7, kBarFontAdvance = 6;

//! 7 rows, top first; bit 4 is the leftmost pixel. nullptr = blank cell.
inline const uint8_t *
BarFontGlyph(char c)
{
	static const uint8_t kLetters[26][7] = {
	    {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, // A
	    {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E}, // B
	    {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E}, // C
	    {0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E}, // D
	    {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F}, // E
	    {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10}, // F
	    {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F}, // G
	    {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, // H
	    {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E}, // I
	    {0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C}, // J
	    {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11}, // K
	    {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F}, // L
	    {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11}, // M
	    {0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11}, // N
	    {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, // O
	    {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10}, // P
	    {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D}, // Q
	    {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11}, // R
	    {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E}, // S
	    {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04}, // T
	    {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, // U
	    {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04}, // V
	    {0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A}, // W
	    {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11}, // X
	    {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04}, // Y
	    {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F}, // Z
	};
	static const uint8_t kDigits[10][7] = {
	    {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}, // 0
	    {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E}, // 1
	    {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}, // 2
	    {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E}, // 3
	    {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}, // 4
	    {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E}, // 5
	    {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E}, // 6
	    {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}, // 7
	    {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}, // 8
	    {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C}, // 9
	};
	static const uint8_t kDash[7] = {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00};
	static const uint8_t kLParen[7] = {0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02};
	static const uint8_t kRParen[7] = {0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08};
	static const uint8_t kLBracket[7] = {0x0E, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0E};
	static const uint8_t kRBracket[7] = {0x0E, 0x02, 0x02, 0x02, 0x02, 0x02, 0x0E};
	static const uint8_t kDot[7] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C};
	static const uint8_t kColon[7] = {0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00};
	static const uint8_t kSlash[7] = {0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10};
	static const uint8_t kPlus[7] = {0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00};
	if (c >= 'a' && c <= 'z') {
		c = (char)(c - 'a' + 'A');
	}
	if (c >= 'A' && c <= 'Z') {
		return kLetters[c - 'A'];
	}
	if (c >= '0' && c <= '9') {
		return kDigits[c - '0'];
	}
	switch (c) {
	case '-': return kDash;
	case '(': return kLParen;
	case ')': return kRParen;
	case '[': return kLBracket;
	case ']': return kRBracket;
	case '.': return kDot;
	case ':': return kColon;
	case '/': return kSlash;
	case '+': return kPlus;
	default: return nullptr;
	}
}

//! Width in pixels of @p s drawn at @p px pixels per font pixel.
inline int
BarFontTextWidth(const char *s, int px)
{
	const int n = (int)std::strlen(s);
	return n > 0 ? (n * kBarFontAdvance - 1) * px : 0;
}

/*!
 * Emit @p s with its top-left at (@p x, @p y), @p px screen pixels per font
 * pixel, as rectangles: @p emit(x, y, w, h) once per horizontal run of lit
 * pixels in a glyph row. Returns the number of rectangles emitted.
 */
template <typename EmitFn>
inline int
BarFontText(const char *s, int x, int y, int px, EmitFn emit)
{
	int count = 0;
	for (; *s != '\0'; s++, x += kBarFontAdvance * px) {
		const uint8_t *g = BarFontGlyph(*s);
		if (g == nullptr) {
			continue;
		}
		for (int row = 0; row < kBarFontH; row++) {
			int col = 0;
			while (col < kBarFontW) {
				if (((g[row] >> (kBarFontW - 1 - col)) & 1) == 0) {
					col++;
					continue;
				}
				const int start = col;
				while (col < kBarFontW && ((g[row] >> (kBarFontW - 1 - col)) & 1) != 0) {
					col++;
				}
				emit(x + start * px, y + row * px, (col - start) * px, px);
				count++;
			}
		}
	}
	return count;
}

} // namespace dxr_demo
