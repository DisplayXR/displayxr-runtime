inline const Glyph *
find(char c)
{
	c = (char)toupper((unsigned char)c);
	for (const Glyph &g : kGlyphs) {
		if (g.c == c) {
			return &g;
		}
	}
	return nullptr;
}

//! Advance per character in unscaled font pixels (5 + 1 spacing).
static const int kAdvance = 6;
static const int kHeight = 7;

inline int
width(const char *s, int sx)
{
	return (int)strlen(s) * kAdvance * sx;
}

/*!
 * Draw @p s into a BGRA8 buffer of @p buf_w x @p buf_h (row pitch buf_w * 4)
 * with its top-left at (@p x, @p y), each font pixel @p sx x @p sy buffer
 * pixels, colour (@p r, @p g, @p b, @p a) written verbatim (premultiply first
 * for an overlay). Clipped to the buffer.
 */
inline void
draw(uint8_t *buf,
     int buf_w,
     int buf_h,
     int x,
     int y,
     const char *s,
     int sx,
     int sy,
     uint8_t r,
     uint8_t g,
     uint8_t b,
     uint8_t a = 255)
{
	for (int ci = 0; s[ci] != '\0'; ci++) {
		const Glyph *gl = find(s[ci]);
		const int ox = x + ci * kAdvance * sx;
		if (gl == nullptr) {
			continue; // space and anything unknown
		}
		for (int row = 0; row < kHeight; row++) {
			for (int col = 0; col < 5; col++) {
				if (gl->rows[row][col] != '#') {
					continue;
				}
				for (int dy = 0; dy < sy; dy++) {
					const int py = y + row * sy + dy;
					if (py < 0 || py >= buf_h) {
						continue;
					}
					for (int dx = 0; dx < sx; dx++) {
						const int px = ox + col * sx + dx;
						if (px < 0 || px >= buf_w) {
							continue;
						}
						uint8_t *p = buf + ((size_t)py * buf_w + px) * 4;
						p[0] = b;
						p[1] = g;
						p[2] = r;
						p[3] = a;
					}
				}
			}
		}
	}
}

//! Fill a rect of a BGRA8 buffer (clipped).
inline void
fill(uint8_t *buf, int buf_w, int buf_h, int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b, uint8_t a)
{
	for (int py = y < 0 ? 0 : y; py < y + h && py < buf_h; py++) {
		for (int px = x < 0 ? 0 : x; px < x + w && px < buf_w; px++) {
			uint8_t *p = buf + ((size_t)py * buf_w + px) * 4;
			p[0] = b;
			p[1] = g;
			p[2] = r;
			p[3] = a;
		}
	}
}

